#!/usr/bin/env python3
"""Brand assets for Appninjas ADB.

    branding/brand.py import <appninjas.se checkout>   copy the master files and colours in
    branding/brand.py generate [--check]                build the app icon from what is in branding/

The Appninjas brand lives in the appninjas.se repository (varumarke/). Its rules: the symbol is used
unchanged, colours come from varumarke/tokens.json, icons from @phosphor-icons/core in the weight fill.
`import` copies exactly those files here, byte for byte, and records the colour values it read.
`generate` places the unchanged symbol paths on an app icon tile. Only its position and the colour
behind `currentColor` are set here, so the logo itself is never redrawn.
"""
import hashlib
import json
import re
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SYMBOL = HERE / "symbol.svg"
COLOURS = HERE / "colours.json"
PHOSPHOR = HERE / "phosphor"
APP_ICON = HERE / "appninjas-adb.svg"

PHOSPHOR_ICONS = [
    "device-mobile", "screencast", "device-rotate", "camera", "terminal-window", "wifi-high",
    "plugs", "arrows-clockwise", "power", "copy", "info", "question",
]

# Token paths in varumarke/tokens.json, resolved through references such as "farg.ljus.accent".
TOKENS = {
    "tile": "farg.ljus.bakgrund",  # the tile behind the symbol, as for apple-touch-icon.png on the site
    "mainForm": "farg.ljus.text",  # what currentColor inherits on the site in light mode
    "band": "logotyp.bandLjus",
}

# The macOS icon grid: a 1024 canvas with an 824 tile, inset 100, corner radius 185.4.
CANVAS, TILE_INSET, TILE_RADIUS = 1024, 100, 185.4
SYMBOL_WIDTH = 560  # leaves more than the clear space (the eye slit's height) on every side


def token(tokens, dotted):
    value = tokens
    for part in dotted.split("."):
        value = value[part]
    return token(tokens, value) if isinstance(value, str) and not value.startswith("#") else value


def do_import(appninjas):
    brand = appninjas / "varumarke"
    source = brand / "logotyp" / "symbol.svg"
    approved = (brand / "godkanda.sha256").read_text()
    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    if f"{digest}  varumarke/logotyp/symbol.svg" not in approved:
        sys.exit("symbol.svg does not match varumarke/godkanda.sha256; use only an approved logo")
    shutil.copyfile(source, SYMBOL)

    tokens = json.loads((brand / "tokens.json").read_text())
    colours = {key: token(tokens, path) for key, path in TOKENS.items()}
    COLOURS.write_text(json.dumps({"source": {k: f"varumarke/tokens.json: {v}" for k, v in TOKENS.items()},
                                   "symbolSha256": digest, **colours}, indent=2) + "\n")

    package = appninjas / "node_modules" / "@phosphor-icons" / "core"
    version = json.loads((package / "package.json").read_text())["version"]
    PHOSPHOR.mkdir(exist_ok=True)
    for name in PHOSPHOR_ICONS:
        shutil.copyfile(package / "assets" / "fill" / f"{name}-fill.svg", PHOSPHOR / f"{name}-fill.svg")
    shutil.copyfile(package / "LICENSE", PHOSPHOR / "LICENSE")
    (PHOSPHOR / "VERSION").write_text(f"@phosphor-icons/core {version}\n")
    print(f"Imported symbol.svg ({digest[:12]}), {len(PHOSPHOR_ICONS)} Phosphor {version} icons, colours {colours}")


def rounded_square(x, size, r):
    end = x + size
    return (f"M{x + r} {x}H{end - r}A{r} {r} 0 0 1 {end} {x + r}V{end - r}A{r} {r} 0 0 1 {end - r} {end}"
            f"H{x + r}A{r} {r} 0 0 1 {x} {end - r}V{x + r}A{r} {r} 0 0 1 {x + r} {x}Z")


def app_icon_svg():
    colours = json.loads(COLOURS.read_text())
    symbol = SYMBOL.read_text()
    width, height = (float(v) for v in re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', symbol).groups())
    scale = SYMBOL_WIDTH / width
    tx, ty = (CANVAS - width * scale) / 2, (CANVAS - height * scale) / 2
    paths = []
    for attributes in re.findall(r"<path\s([^>]*?)/?>", symbol):
        coloured = attributes.replace('fill="currentColor"', f'fill="{colours["mainForm"]}"')
        paths.append(f'  <path transform="matrix({scale:.6g} 0 0 {scale:.6g} {tx:.6g} {ty:.6g})" {coloured}/>')
    return "\n".join([
        "<!-- Generated by branding/brand.py from symbol.svg and colours.json. Do not edit. -->",
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {CANVAS} {CANVAS}" width="{CANVAS}" height="{CANVAS}">',
        "  <title>Appninjas ADB</title>",
        f'  <path fill="{colours["tile"]}" d="{rounded_square(TILE_INSET, CANVAS - 2 * TILE_INSET, TILE_RADIUS)}"/>',
        *paths,
        "</svg>",
    ]) + "\n"


def do_generate(check):
    expected = app_icon_svg()
    if check:
        if not APP_ICON.exists() or APP_ICON.read_text() != expected:
            sys.exit(f"{APP_ICON.name} is out of date: run branding/brand.py generate")
        print(f"{APP_ICON.name} is up to date")
        return
    APP_ICON.write_text(expected)
    print(f"Wrote {APP_ICON}")


if __name__ == "__main__":
    args = sys.argv[1:]
    if len(args) == 2 and args[0] == "import":
        do_import(Path(args[1]).expanduser())
        do_generate(check=False)
    elif args[:1] == ["generate"] and args[1:] in ([], ["--check"]):
        do_generate(check=args[1:] == ["--check"])
    else:
        sys.exit(__doc__)
